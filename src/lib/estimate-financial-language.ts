export const summaryText = (locale: CompanyLocale) => (label: keyof typeof summarySpanish) =>
  locale === "es" ? summarySpanish[label] : label;

export function financialChargeDescription(locale: CompanyLocale, line: EstimateCustomerChargeSummary["lines"][number]) {
  if (line.origin === "SYSTEM") {
    const t = summaryText(locale);
    if (line.source === "INSTALLATION" && line.description === "Installation") return t("Installation");
    if (line.source === "PERMIT" && line.description === "Permit Fee") return t("Permit Fee");
    if (line.source === "CITY_FEE" && line.description === "City Fee") return t("City Fee");
  }
  return line.description;
}
