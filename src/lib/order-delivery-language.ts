export function deliveryError(locale: CompanyLocale, error: unknown) {
  const message = error instanceof Error ? error.message : "";
  if (locale === "en") return message || "Could not update the order. Please try again.";
  return spanishErrors.get(message) ?? (message || "No se pudo actualizar la orden. Vuelve a intentarlo.");
}
